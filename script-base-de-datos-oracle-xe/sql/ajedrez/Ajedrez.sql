	ADD CONSTRAINT FK_PARTIDA_ARBITRO FOREIGN KEY (ARBITRO) REFERENCES AJEDREZ.PARTICIPANTES
	ADD CONSTRAINT FK_PARTIDA_GANADOR FOREIGN KEY (GANADOR) REFERENCES AJEDREZ.JUGADORES
	ADD CONSTRAINT FK_PARTIDA_SALA FOREIGN KEY (SALA) REFERENCES AJEDREZ.SALAS;
	
