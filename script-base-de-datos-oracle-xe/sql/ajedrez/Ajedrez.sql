ALTER TABLE AJEDREZ.JUGADORES 
    ADD CONSTRAINT FK_JUGADOR_PARTIC FOREIGN KEY (N_ASOCIADO) REFERENCES AJEDREZ.PARTICIPANTES;
    
ALTER TABLE AJEDREZ.ALOJAMIENTOS
    ADD CONSTRAINT FK_ALOJ_PARTIC FOREIGN KEY (PARTICIPANTE) REFERENCES AJEDREZ.PARTICIPANTES
	ADD CONSTRAINT FK_ALOJ_HOTEL FOREIGN KEY (HOTEL) REFERENCES AJEDREZ.HOTELES;
	
ALTER TABLE AJEDREZ.PAISES
    ADD CONSTRAINT FK_PAIS_PAIS FOREIGN KEY (PAIS_Q_LO_REPRESENTA)REFERENCES AJEDREZ.PAISES;

ALTER TABLE AJEDREZ.CONTRINCANTES
    ADD CONSTRAINT FK_CONTRIN_PARTIDA FOREIGN KEY (PARTIDA) REFERENCES AJEDREZ.PARTIDAS
    ADD CONSTRAINT FK_CONTRIN_JUGADOR FOREIGN KEY (JUGADOR) REFERENCES AJEDREZ.JUGADORES;
   
ALTER TABLE AJEDREZ.MOVIMIENTOS
	ADD CONSTRAINT FK_MOV_PARTIDA FOREIGN KEY (PARTIDA) REFERENCES AJEDREZ.PARTIDAS;
	
