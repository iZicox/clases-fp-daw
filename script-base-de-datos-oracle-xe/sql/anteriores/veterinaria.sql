-- tablas proveedores

CREATE TABLE proveedores (
proveedor_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
cif VARCHAR2(12) UNIQUE NOT NULL,
nombre_empresa VARCHAR2(80) NOT NULL,
telefono VARCHAR2(15) NOT NULL,
email VARCHAR2(60) UNIQUE
);

CREATE TABLE productos_veterinarios (
producto_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
codigo_barras NUMBER(13) UNIQUE NOT NULL,
nombre_producto VARCHAR2(100) NOT NULL,
tipo_producto VARCHAR(30) 
CONSTRAINT ck_tipo_producto CHECK (tipo_producto IN ('Medicamento', 'Alimento', 'Accesorio', 'Higiene')),
proveedor_id NUMBER NOT NULL,
precio_compra NUMBER(8,2) CHECK (PRECIO_COMPRA > 0),
precio_venta NUMBER(8,2) CHECK (PRECIO_VENTA > 0),
stock_actual NUMBER(5) DEFAULT 0 CHECK (stock_actual >= 0),
stock_minimo NUMBER(5) CHECK (STOCK_MINIMO >= 0),
CONSTRAINT fk_prov_id_prod_vet FOREIGN KEY (proveedor_id) REFERENCES PROVEEDORES (proveedor_id)
);

CREATE TABLE ventas (
venta_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
fecha_venta TIMESTAMP DEFAULT SYSTIMESTAMP,
propietario_id NUMBER,
total NUMBER(10,2) CHECK (total > 0),
CONSTRAINT fk_prop_id_ventas FOREIGN KEY (propietario_id) REFERENCES PROPIETARIOS (propietario_id)
);

CREATE TABLE detalles_venta (
venta_id NUMBER,
producto_id NUMBER,
cantidad NUMBER(5) CHECK (cantidad > 0),
precio_unitario NUMBER(8,2) CHECK (precio_unitario > 0),
subtotal NUMBER(10,2) CHECK (subtotal > 0),
CONSTRAINT pk_detalles_venta PRIMARY KEY (venta_id, producto_id),
CONSTRAINT fk_venta_id FOREIGN KEY (venta_id) REFERENCES VENTAS (venta_id),
CONSTRAINT fk_producto_vet FOREIGN KEY (producto_id) REFERENCES PRODUCTOS_VETERINARIOS (producto_id)
);

