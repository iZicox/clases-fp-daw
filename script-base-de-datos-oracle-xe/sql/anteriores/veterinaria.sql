
-- 1
CREATE TABLE propietarios (
propietario_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
dni VARCHAR2(9) UNIQUE NOT NULL,
nombre_completo VARCHAR2(80) NOT NULL,
direccion VARCHAR2(150),
telefono VARCHAR2(15) NOT NULL,
email VARCHAR2(60) UNIQUE
);


-- 2

CREATE TABLE veterinarios (
veterinario_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
num_colegiado VARCHAR2(20) UNIQUE NOT NULL,
nombre VARCHAR2(50) NOT NULL,
apellidos VARCHAR2(70) NOT NULL,
especialidad VARCHAR2(40), 
fecha_alta DATE DEFAULT SYSDATE,
salario NUMBER(9,2),
CONSTRAINT chk_especialidad_tipo CHECK (especialidad IN ('Medicina General', 'Cirugia', 
'Dermatologo', 'Oftalmologia', 'Traumatologia')),
CONSTRAINT chk_salario_rango CHECK (salario BETWEEN 2000 AND 8000)
);

ALTER TABLE VETERINARIOS ADD CONSTRAINT pk_vet_id PRIMARY KEY (veterinario_id);

-- 3

CREATE TABLE mascotas (
mascota_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
chip VARCHAR2(15) UNIQUE NOT NULL,
nombre VARCHAR2(40) NOT NULL,
especie VARCHAR2(30) CHECK (especie IN ('Perro', 'Gato', 'Ave', 'Roedor', 'Reptil')),
raza VARCHAR2(50),
fecha_nacimiento DATE,
peso NUMBER(5,2) CHECK (peso > 0),
propietario_id NUMBER,
CONSTRAINT fk_propietario_id FOREIGN KEY (propietario_id) REFERENCES PROPIETARIOS (propietario_id)
);



-- 4

CREATE TABLE citas (
cita_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
mascota_id NUMBER NOT NULL,
veterinario_id NUMBER NOT NULL,
fecha_hora TIMESTAMP NOT NULL,
motivo VARCHAR2(200) NOT NULL,
estado VARCHAR2(20) CHECK (estado IN ('Programada', 'Realizada', 'Cancelada', 'No Asistio')),
observaciones VARCHAR2(500),
CONSTRAINT fk_mascota_id FOREIGN KEY (mascota_id) REFERENCES MASCOTAS (mascota_id),
CONSTRAINT fk_veterinario_id FOREIGN KEY (veterinario_id) REFERENCES VETERINARIOS (veterinario_id)
);


-- 5 

CREATE TABLE tratamientos (
tratamiento_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
codigo VARCHAR2(10) UNIQUE NOT NULL,
nombre VARCHAR2(60)NOT NULL,
descripcion VARCHAR2(200),
coste NUMBER(8,2) CHECK (coste > 0)
);

CREATE TABLE historial_tratamientos (
mascota_id NUMBER NOT NULL,
tratamiento_id NUMBER NOT NULL,
fecha_aplicacion DATE NOT NULL,
veterinario_id NUMBER NOT NULL,
dosis VARCHAR2(50),
notas VARCHAR2(300),
-- primary key compuesta
CONSTRAINT pk_historial_tratamientos PRIMARY KEY (mascota_id, tratamiento_id, fecha_aplicacion),

-- foreign key
CONSTRAINT fk_mascota_id_historial_tratamientos FOREIGN KEY (mascota_id) REFERENCES MASCOTAS (mascota_id),
CONSTRAINT fk_tratamiento_id_historial_tratamientos FOREIGN KEY (tratamiento_id) REFERENCES TRATAMIENTOS (tratamiento_id),
CONSTRAINT fk_veterinario_id_historial_tratamientos FOREIGN KEY (veterinario_id) REFERENCES VETERINARIOS (veterinario_id)
);

