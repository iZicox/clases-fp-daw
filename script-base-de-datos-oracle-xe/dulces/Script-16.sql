CREATE TABLE CAJAS(
	idcaja		varchar2(4),
	nombre		varchar2(50),
	tamano 		number(2),
	precio		number(5,1),
	existencias	number(4),
CONSTRAINT pk_cajas PRIMARY KEY(idcaja)
);

CREATE TABLE DETALLE_CAJAS(
	idcaja	    varchar2(4),
	idbombon	varchar2(3),
	cantidad	number(2),
CONSTRAINT pk_detalle_cajas PRIMARY KEY(idcaja, idbombon)
);

CREATE TABLE BOMBONES(
	idbombon	varchar2(3),
	nombre 	    varchar2(30),
	chocolate	varchar2(30),
	nuez		varchar2(30),
	relleno	    varchar2(30),
	coste		number(3,1),
CONSTRAINT pk_bombones PRIMARY KEY(idbombon)	
);

CREATE TABLE CLIENTES(
	idcliente	number(3),
	apellidos	varchar2(25),
	nombre		varchar2(20),
	ciudad		varchar2(15),
	pais		varchar2(15),
	fecha_alta	date,
CONSTRAINT pk_clientes PRIMARY KEY(idcliente)
);

CREATE TABLE PEDIDOS(
	idpedido		number(3),
	idcliente		number(3),
	fecha_pedido	date,
	regalo		number(1),
	fecha_envio		date,
CONSTRAINT pk_pedidos PRIMARY KEY(idpedido)
);

CREATE TABLE DETALLE_PEDIDOS(
	idpedido	number(3),
	idcaja	    varchar2(4),
	cantidad	number(3),
CONSTRAINT pk_DETALLE_PEDIDOS PRIMARY KEY(idpedido, idcaja)
);

ALTER TABLE PEDIDOS
	ADD CONSTRAINT fk_1 FOREIGN KEY(idcliente) REFERENCES CLIENTES;
ALTER TABLE DETALLE_PEDIDOS
	ADD CONSTRAINT fk_2 FOREIGN KEY(idpedido) REFERENCES PEDIDOS
	ADD CONSTRAINT fk_3 FOREIGN KEY(idcaja) REFERENCES CAJAS;
ALTER TABLE DETALLE_CAJAS
	ADD CONSTRAINT fk_4 FOREIGN KEY(idcaja) REFERENCES CAJAS
    ADD CONSTRAINT fk_5 FOREIGN KEY(idbombon) REFERENCES BOMBONES;

