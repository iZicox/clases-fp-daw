CREATE OR REPLACE VIEW MODULO_EXTENSO AS
SELECT DISTINCT
        CI.NOMBRE CICLO,
        MAX(MO.HORAS) 
FROM CICLO CI 
INNER JOIN MODULO_IMPARTIDO MOI ON MOI.COD_CICLO = CI.COD_CICLO 
INNER JOIN MODULO MO ON MO.COD_MODULO = MOI.COD_MODULO
GROUP BY CI.NOMBRE;

