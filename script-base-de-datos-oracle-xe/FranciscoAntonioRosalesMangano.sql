SELECT DISTINCT
        AL.COD_ALUMNO,
        AL.NOMBRE,
        AL.APELLIDOS
FROM ALUMNO AL 
INNER JOIN PROFESOR P ON P.COD_PROFESOR = AL.TUTOR
INNER JOIN MATRICULA M ON M.COD_ALUMNO = AL.COD_ALUMNO
LEFT JOIN DETALLE_MATRICULA DM ON DM.COD_MATRICULA = M.COD_MATRICULA 
WHERE P.COD_DEPARTAMENTO = '003'
AND DM.COD_MODULO NOT IN ('0179');

