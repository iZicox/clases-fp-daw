CREATE OR REPLACE VIEW GASTO_POR_ALUMNO AS
SELECT 
        AL.COD_ALUMNO AS COD_ALUMNO,
        AL.NOMBRE AS NOMBRE,
        AL.APELLIDOS AS APELLIDOS, 
        SUM(M.IMPORTE) AS IMPORTE_TOTAL
FROM ALUMNO AL
INNER JOIN MATRICULA M ON AL.COD_ALUMNO = M.COD_ALUMNO
GROUP BY AL.COD_ALUMNO,AL.NOMBRE, AL.APELLIDOS;

