-- 2. CREACIÓN DE TABLAS (Sin datos, solo estructura)

CREATE TABLE INSTITUTO.DEPARTAMENTO (
    COD_DEPARTAMENTO VARCHAR2(3) PRIMARY KEY,
    NOMBRE VARCHAR2(60 CHAR) NOT NULL UNIQUE,
    PRESUPUESTO NUMBER(8, 2) NOT NULL
);

CREATE TABLE INSTITUTO.CICLO (
    COD_CICLO VARCHAR2(10 CHAR) PRIMARY KEY,
    NOMBRE VARCHAR2(60 CHAR) NOT NULL, 
    TIPO VARCHAR2(2) NOT NULL CHECK (TIPO IN ('GM', 'GS')) 
);

CREATE TABLE INSTITUTO.MODULO (
    COD_MODULO VARCHAR2(6) PRIMARY KEY,
    NOMBRE VARCHAR2(60 CHAR) NOT NULL,
    CURSO NUMBER(1) NOT NULL CHECK (CURSO IN (1,2)),
    HORAS NUMBER(3) NOT NULL
);

CREATE TABLE INSTITUTO.PROFESOR (
    COD_PROFESOR VARCHAR2(3) PRIMARY KEY,
    NOMBRE VARCHAR2(20) NOT NULL,
    APELLIDOS VARCHAR2(40) NOT NULL,
    FECHA_ALTA DATE DEFAULT SYSDATE,
    COD_DEPARTAMENTO VARCHAR2(3) REFERENCES INSTITUTO.DEPARTAMENTO(COD_DEPARTAMENTO)
);

-- (Añadimos la relación circular de Jefe Dpto después de crear INSTITUTO.PROFESOR)
ALTER TABLE INSTITUTO.DEPARTAMENTO ADD (JEFE_DPTO VARCHAR2(3) REFERENCES INSTITUTO.PROFESOR(COD_PROFESOR));

CREATE TABLE INSTITUTO.MODULO_IMPARTIDO (
    COD_CICLO VARCHAR2(10 CHAR) NOT NULL REFERENCES INSTITUTO.CICLO(COD_CICLO),
    COD_MODULO VARCHAR2(6) NOT NULL REFERENCES INSTITUTO.MODULO(COD_MODULO), 
    COD_PROFESOR VARCHAR2(3) NOT NULL REFERENCES INSTITUTO.PROFESOR(COD_PROFESOR),
    AULA VARCHAR2(10) NOT NULL,
    PRIMARY KEY(COD_CICLO, COD_MODULO)
);

CREATE TABLE INSTITUTO.ALUMNO (
    COD_ALUMNO VARCHAR2(4) PRIMARY KEY,
    NOMBRE VARCHAR2(20) NOT NULL,
    APELLIDOS VARCHAR2(40) NOT NULL,
    FECHA_NACIMIENTO DATE, 
    TELEFONO VARCHAR2(11) NOT NULL,
    DIRECCION VARCHAR2(60), 
    COD_POSTAL VARCHAR2(5), 
    TUTOR VARCHAR2(3) REFERENCES INSTITUTO.PROFESOR(COD_PROFESOR), 
    DELEGADO VARCHAR2(4) REFERENCES INSTITUTO.ALUMNO(COD_ALUMNO)
);

CREATE TABLE INSTITUTO.MATRICULA (
    COD_MATRICULA VARCHAR2(10) PRIMARY KEY,
    COD_ALUMNO VARCHAR2(4) NOT NULL REFERENCES INSTITUTO.ALUMNO(COD_ALUMNO),
    COD_CICLO VARCHAR2(10 CHAR) NOT NULL REFERENCES INSTITUTO.CICLO(COD_CICLO),
    CURSO NUMBER(1) NOT NULL CHECK (CURSO IN (1, 2)), 
    CURSO_ACADEMICO VARCHAR2(9) DEFAULT '2025/2026', 
    FECHA_MATRICULA DATE NOT NULL, 
    IMPORTE NUMBER(6,2) DEFAULT 0,
    UNIQUE(COD_ALUMNO, COD_CICLO, CURSO_ACADEMICO)
);

CREATE TABLE INSTITUTO.DETALLE_MATRICULA (
    COD_MATRICULA VARCHAR2(10) REFERENCES INSTITUTO.MATRICULA(COD_MATRICULA) ON DELETE CASCADE,
    COD_MODULO VARCHAR2(6) REFERENCES INSTITUTO.MODULO(COD_MODULO),
    NOTA_FINAL NUMBER(4,2) CHECK (NOTA_FINAL BETWEEN 0 AND 10),
    PRIMARY KEY (COD_MATRICULA, COD_MODULO)
);

