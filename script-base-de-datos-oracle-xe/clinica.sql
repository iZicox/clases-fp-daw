SELECT 
        M.CURSO_ACADEMICO CURSO,
        COUNT(M.COD_ALUMNO) ALUMNOS,
        COUNT(DISTINCT DM.COD_MODULO) MODULOS,
        ROUND(AVG(DM.NOTA_FINAL),2) NOTA_MEDIA,
        MAX(DM.NOTA_FINAL) NOTA_MAS_ALTA,
        MIN(M.FECHA_MATRICULA) PRIMERA_MATRICULACION
FROM MATRICULA M 
INNER JOIN DETALLE_MATRICULA DM ON DM.COD_MATRICULA = M.COD_MATRICULA
GROUP BY M.CURSO_ACADEMICO;

--6
SELECT 
        P.COD_PROFESOR,
        P.NOMBRE,
        P.APELLIDOS,
        CASE
            WHEN MO.NOMBRE IS NULL 
            THEN 'NO DOCENTE' 
            ELSE MO.NOMBRE 
        END AS MODULO
FROM PROFESOR P 
LEFT JOIN MODULO_IMPARTIDO MOI ON MOI.COD_PROFESOR = P.COD_PROFESOR 
LEFT JOIN MODULO MO ON MO.COD_MODULO = MOI.COD_MODULO
ORDER BY P.APELLIDOS;

--7
SELECT 
        AL.NOMBRE,
        AL.APELLIDOS,
        AL.FECHA_NACIMIENTO,
        AL.DIRECCION,
        SUM(M.IMPORTE), 
        M.CURSO_ACADEMICO --SIN ESTE CAMPO NO ME FUNCIONABA
FROM ALUMNO AL 
INNER JOIN MATRICULA M ON M.COD_ALUMNO = AL.COD_ALUMNO
WHERE TO_CHAR(AL.FECHA_NACIMIENTO,'YYYY') IN ('2006','2004')
AND UPPER(AL.DIRECCION) LIKE '%MA%'
GROUP BY 
        AL.NOMBRE,
        AL.APELLIDOS,
        AL.FECHA_NACIMIENTO,
        AL.DIRECCION,
        M.CURSO_ACADEMICO
HAVING SUM(M.IMPORTE) > 100 AND M.CURSO_ACADEMICO = '2025/2026';

