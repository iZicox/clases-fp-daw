-- 13. GENERACIÓN DE HISTÓRICO MASIVO (CURSO 2024/2025)
-- ==========================================================

-- A) GENERAR MATRÍCULAS DEL CURSO PASADO
-- Lógica:
-- 1. Si el alumno está en 2º este año (y no es repetidor de 2º), el año pasado estaba en 1º.
-- 2. Si el alumno es repetidor (de 1º o 2º), el año pasado estaba en el mismo curso.

INSERT INTO MATRICULA (COD_MATRICULA, COD_ALUMNO, COD_CICLO, CURSO, CURSO_ACADEMICO, FECHA_MATRICULA, IMPORTE)
SELECT 
    'H-' || COD_ALUMNO, -- ID Diferenciado
    COD_ALUMNO,
    COD_CICLO,
    CASE 
        -- Si son los repetidores conocidos de 2º (A115, A150), estaban en 2º
        WHEN COD_ALUMNO IN ('A115', 'A150') THEN 2
        -- Si son los repetidores conocidos de 1º (A022, A062), estaban en 1º
        WHEN COD_ALUMNO IN ('A022', 'A062') THEN 1
        -- Si es un alumno de 2º normal, estaba en 1º
        WHEN CURSO = 2 THEN 1
        -- Si es un alumno de 1º normal, asumimos que NO estaba matriculado (o repetimos 1º para dar volumen)
        -- Para no duplicar PKs con lógica compleja, en este script masivo nos centramos en generar historial 
        -- para los que PROMOCIONARON o REPITIERON con certeza.
        ELSE NULL 
    END AS CURSO_ANTERIOR,
    '2024/2025',
    -- Fecha aleatoria entre 1 Julio y 30 Septiembre 2024
    TO_DATE('01/07/2024', 'DD/MM/YYYY') + TRUNC(DBMS_RANDOM.VALUE(0, 90)),
    -- Importe aleatorio entre 80.00 y 150.00
    ROUND(DBMS_RANDOM.VALUE(80, 150), 2)
FROM MATRICULA
WHERE CURSO_ACADEMICO = '2025/2026'
-- Filtramos solo los casos que nos interesan generar (Actuales 2º + Repetidores conocidos)
AND (CURSO = 2 OR COD_ALUMNO IN ('A022', 'A062'));


-- B) GENERAR DETALLES (MÓDULOS) DEL CURSO PASADO
-- Insertamos todas las asignaturas correspondientes al curso en el que estaban
INSERT INTO DETALLE_MATRICULA (COD_MATRICULA, COD_MODULO, NOTA_FINAL)
SELECT 
    M.COD_MATRICULA,
    MI.COD_MODULO,
    -- Nota aleatoria con 2 decimales entre 1 y 10
    TRUNC(DBMS_RANDOM.VALUE(1, 10), 2)
FROM MATRICULA M
-- Unimos con lo que se imparte en ese ciclo
JOIN MODULO_IMPARTIDO MI ON M.COD_CICLO = MI.COD_CICLO
-- Unimos con Módulo para saber a qué curso pertenece la asignatura
JOIN MODULO MOD ON MI.COD_MODULO = MOD.COD_MODULO
WHERE M.CURSO_ACADEMICO = '2024/2025'
-- Condición vital: Solo insertamos módulos del curso en el que estaba el alumno
AND MOD.CURSO = M.CURSO;

