CREATE OR REPLACE VIEW VISTA_TUTORES AS
SELECT DISTINCT
        P.NOMBRE AS NOMBRE,
        P.APELLIDOS AS APELLIDO,
        CASE 
            WHEN P.COD_PROFESOR = AL.TUTOR
            THEN 'SI' ELSE 'NO'
        END AS TUTOR
FROM PROFESOR P
LEFT JOIN ALUMNO AL ON AL.TUTOR = P.COD_PROFESOR;

--3

SELECT
        CI.NOMBRE AS CICLO,
        MO.NOMBRE AS MODULO,
        P.NOMBRE AS NOMBRE,
        P.APELLIDOS AS APELLIDOS,
        D.NOMBRE AS DEPT
FROM DEPARTAMENTO D 
INNER JOIN PROFESOR P ON D.COD_DEPARTAMENTO = P.COD_DEPARTAMENTO 
INNER JOIN MODULO_IMPARTIDO MOI ON MOI.COD_PROFESOR = P.COD_PROFESOR
INNER JOIN MODULO MO ON MO.COD_MODULO = MOI.COD_MODULO
INNER JOIN CICLO CI ON CI.COD_CICLO = MOI.COD_CICLO
WHERE SUBSTR(P.NOMBRE,1,1) = (
    SELECT SUBSTR(D2.NOMBRE,1,1)
    FROM DEPARTAMENTO D2
    WHERE D2.COD_DEPARTAMENTO = P.COD_DEPARTAMENTO
)
AND MO.HORAS BETWEEN 90 AND 120;
